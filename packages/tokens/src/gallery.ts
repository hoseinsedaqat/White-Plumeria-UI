import { contrastRatio, relativeLuminance } from './contrast.ts';
import type { ColorTokens, ThemeDefinition, ThemeName } from './types.ts';

/**
 * Extra palettes for the homepage theme list.
 * Names and colors are original. They are not copied from another library.
 */

type Face = {
  bg: string;
  surface: string;
  muted: string;
  text: string;
  primary: string;
  accent: string;
  success: string;
  warning: string;
  danger: string;
  info: string;
  border: string;
};

function hexToRgb(hex: string): [number, number, number] {
  const raw = hex.replace('#', '');
  return [
    Number.parseInt(raw.slice(0, 2), 16),
    Number.parseInt(raw.slice(2, 4), 16),
    Number.parseInt(raw.slice(4, 6), 16),
  ];
}

function mix(a: string, b: string, amount: number): string {
  const [ar, ag, ab] = hexToRgb(a);
  const [br, bg, bb] = hexToRgb(b);
  const channel = (left: number, right: number) =>
    Math.round(left + (right - left) * amount)
      .toString(16)
      .padStart(2, '0');
  return `#${channel(ar, br)}${channel(ag, bg)}${channel(ab, bb)}`.toUpperCase();
}

function apart(color: string, blocked: string[]): string {
  let next = color.toUpperCase();
  let step = 0;
  while (blocked.some((item) => item.toLowerCase() === next.toLowerCase()) && step < 10) {
    next = mix(next, step % 2 === 0 ? '#000000' : '#FFFFFF', 0.08 + step * 0.03);
    step += 1;
  }
  return next;
}

function readable(bg: string): string {
  const dark = '#14120F';
  const light = '#FFFCF7';
  const darkScore = contrastRatio(dark, bg) ?? 0;
  const lightScore = contrastRatio(light, bg) ?? 0;
  return darkScore >= lightScore ? dark : light;
}

function paintable(color: string): { bg: string; fg: string } {
  let bg = color.toUpperCase();
  for (let step = 0; step < 14; step += 1) {
    const fg = readable(bg);
    if ((contrastRatio(fg, bg) ?? 0) >= 4.5) return { bg, fg };
    const lum = relativeLuminance(bg) ?? 0.5;
    bg = mix(bg, lum > 0.45 ? '#FFFFFF' : '#000000', 0.14);
  }
  return { bg, fg: readable(bg) };
}

function readableText(bg: string, surface: string, preferred: string): string {
  const candidates = [preferred, '#14120F', '#0C0A09', '#1C1917', '#FAF7F2', '#FFFFFF', '#FFF7ED'];
  for (const color of candidates) {
    if ((contrastRatio(color, bg) ?? 0) >= 4.5 && (contrastRatio(color, surface) ?? 0) >= 4.5) {
      return color.toUpperCase();
    }
  }
  const black = '#000000';
  const white = '#FFFFFF';
  const blackScore = Math.min(contrastRatio(black, bg) ?? 0, contrastRatio(black, surface) ?? 0);
  const whiteScore = Math.min(contrastRatio(white, bg) ?? 0, contrastRatio(white, surface) ?? 0);
  return blackScore >= whiteScore ? black : white;
}

function withAlpha(hex: string, alpha: number): string {
  const [r, g, b] = hexToRgb(hex);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

function paint(face: Face): ColorTokens {
  const bg = face.bg.toUpperCase();
  const surface = apart(face.surface, [bg]);
  const muted = apart(face.muted, [bg, surface]);
  const text = readableText(bg, surface, face.text);
  const primary = paintable(face.primary);
  let warning = paintable(face.warning);
  let danger = paintable(face.danger);
  if (warning.bg.toLowerCase() === primary.bg.toLowerCase()) warning = paintable(mix(warning.bg, '#000000', 0.22));
  if (danger.bg.toLowerCase() === primary.bg.toLowerCase()) danger = paintable(mix(danger.bg, '#FFFFFF', 0.28));
  const accent = paintable(face.accent);
  const success = paintable(face.success);
  const info = paintable(face.info);
  const border = apart(face.border, [bg, surface, muted]);
  return {
    bg,
    bgMuted: muted,
    bgSubtle: apart(mix(bg, muted, 0.45), [bg, surface, muted]),
    surface,
    surfaceRaised: apart(mix(surface, text, 0.06), [bg, surface, muted]),
    text,
    textMuted: mix(text, bg, 0.32),
    textSubtle: mix(text, bg, 0.48),
    textInverse: readable(text),
    border,
    borderStrong: mix(border, text, 0.42),
    focus: primary.bg,
    primary: primary.bg,
    primaryHover: mix(primary.bg, text, 0.14),
    primaryActive: mix(primary.bg, text, 0.26),
    primaryFg: primary.fg,
    primarySubtle: mix(bg, primary.bg, 0.16),
    accent: accent.bg,
    accentFg: accent.fg,
    success: success.bg,
    successFg: success.fg,
    successSubtle: mix(bg, success.bg, 0.16),
    warning: warning.bg,
    warningFg: warning.fg,
    warningSubtle: mix(bg, warning.bg, 0.16),
    danger: danger.bg,
    dangerFg: danger.fg,
    dangerSubtle: mix(bg, danger.bg, 0.14),
    info: info.bg,
    infoFg: info.fg,
    infoSubtle: mix(bg, info.bg, 0.14),
    disabledBg: apart(mix(bg, muted, 0.62), [bg, surface, muted]),
    disabledFg: mix(text, bg, 0.48),
    overlay: 'rgba(12, 10, 8, 0.55)',
    shadow: 'rgba(12, 10, 8, 0.16)',
    ring: withAlpha(primary.bg, 0.4),
  };
}

function theme(
  name: ThemeName,
  label: string,
  labelFa: string,
  description: string,
  descriptionFa: string,
  light: Face,
  dark: Face,
): ThemeDefinition {
  return {
    name,
    label,
    labelFa,
    description,
    descriptionFa,
    light: paint(light),
    dark: paint(dark),
  };
}

